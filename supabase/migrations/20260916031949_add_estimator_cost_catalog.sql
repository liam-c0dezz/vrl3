-- Versioned, server-only source catalog for the universal construction scope engine.
-- The Edge Function accesses this table with the service role. Client roles receive
-- no table or RPC privileges.

create table public.estimator_cost_items (
  id bigint generated by default as identity primary key,
  catalog_version text not null,
  source_row integer not null,
  category text not null,
  description text not null,
  material_cost numeric(14, 4) not null default 0,
  labor_cost numeric(14, 4) not null default 0,
  equipment_cost numeric(14, 4) not null default 0,
  direct_cost numeric(14, 4) not null,
  unit text not null,
  crew_code text not null default '',
  trade text not null,
  action text not null,
  object_key text not null,
  process_role text not null,
  attributes jsonb not null default '{}'::jsonb,
  residential_eligible boolean not null default true,
  tag_confidence numeric(5, 4) not null default 0,
  search_document tsvector generated always as (
    to_tsvector(
      'english',
      coalesce(category, '') || ' ' ||
      coalesce(description, '') || ' ' ||
      coalesce(trade, '') || ' ' ||
      coalesce(object_key, '') || ' ' ||
      coalesce(process_role, '')
    )
  ) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint estimator_cost_items_catalog_source_unique
    unique (catalog_version, source_row),
  constraint estimator_cost_items_source_row_positive
    check (source_row > 1),
  constraint estimator_cost_items_confidence_range
    check (tag_confidence between 0 and 1),
  constraint estimator_cost_items_attributes_object
    check (jsonb_typeof(attributes) = 'object')
);

create index estimator_cost_items_catalog_version_idx
  on public.estimator_cost_items (catalog_version);
create index estimator_cost_items_lookup_idx
  on public.estimator_cost_items (
    catalog_version, residential_eligible, process_role, trade, object_key
  );
create index estimator_cost_items_search_idx
  on public.estimator_cost_items using gin (search_document);
create index estimator_cost_items_attributes_idx
  on public.estimator_cost_items using gin (attributes jsonb_path_ops);

alter table public.estimator_cost_items enable row level security;
revoke all on table public.estimator_cost_items from public, anon, authenticated;
grant select, insert, update, delete on table public.estimator_cost_items to service_role;
grant usage, select on sequence public.estimator_cost_items_id_seq to service_role;

create or replace function public.search_estimator_cost_items(
  p_catalog_version text,
  p_process_role text,
  p_trade text default null,
  p_object_key text default null,
  p_search_terms text[] default array[]::text[],
  p_limit integer default 12
)
returns table (
  id bigint,
  catalog_version text,
  source_row integer,
  category text,
  description text,
  material_cost numeric,
  labor_cost numeric,
  equipment_cost numeric,
  direct_cost numeric,
  unit text,
  crew_code text,
  trade text,
  action text,
  object_key text,
  process_role text,
  attributes jsonb,
  residential_eligible boolean,
  tag_confidence numeric,
  match_score double precision
)
language sql
stable
security invoker
set search_path = ''
as $$
  with query_input as (
    select case
      when cardinality(coalesce(p_search_terms, array[]::text[])) = 0 then null
      else plainto_tsquery('english', array_to_string(p_search_terms, ' '))
    end as query
  )
  select
    item.id,
    item.catalog_version,
    item.source_row,
    item.category,
    item.description,
    item.material_cost,
    item.labor_cost,
    item.equipment_cost,
    item.direct_cost,
    item.unit,
    item.crew_code,
    item.trade,
    item.action,
    item.object_key,
    item.process_role,
    item.attributes,
    item.residential_eligible,
    item.tag_confidence,
    (
      case when item.process_role = p_process_role then 12 else 0 end +
      case when p_trade is not null and item.trade = p_trade then 5 else 0 end +
      case when p_object_key is not null and item.object_key = p_object_key then 10 else 0 end +
      case when query_input.query is null then 0
        else ts_rank_cd(item.search_document, query_input.query) * 8 end +
      item.tag_confidence
    )::double precision as match_score
  from public.estimator_cost_items as item
  cross join query_input
  where item.catalog_version = p_catalog_version
    and item.residential_eligible
    and item.process_role = p_process_role
    and (p_trade is null or item.trade = p_trade or item.trade = 'general')
    and (p_object_key is null or item.object_key = p_object_key or item.object_key = 'other')
    and (
      query_input.query is null or
      item.search_document @@ query_input.query or
      item.object_key = p_object_key
    )
  order by match_score desc, item.direct_cost asc, item.source_row asc
  limit greatest(1, least(coalesce(p_limit, 12), 25));
$$;

revoke all on function public.search_estimator_cost_items(
  text, text, text, text, text[], integer
) from public, anon, authenticated;
grant execute on function public.search_estimator_cost_items(
  text, text, text, text, text[], integer
) to service_role;
